"""How much of Anchore's API the collector lands on the grid (req-anchore-coverage).

    python -m tap_plugin.anchore.contract.coverage            # print the spec's coverage section
    python -m tap_plugin.anchore.contract.coverage --check    # exit 1 when the spec's section is stale

The target is to import everything Anchore holds about artifacts and running containers. Every GET
in the committed vendor file is one of: landed (the collector reads it), excluded (with the reason,
from coverage.json) or planned (not yet built). The target is hit when nothing is planned. Reads
only committed files and takes no path from its arguments.
"""

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from tap_plugin.anchore.contract.build import SOURCE

HERE = Path(__file__).resolve().parent
RULES = HERE / "coverage.json"
MANIFEST = HERE.parent / "collectors" / "anchore_collector" / "manifest.json"
SPEC = HERE.parents[2] / "specs" / "spec-anchore-v0.md"
BEGIN = "<!-- coverage:begin (generated by tap_plugin.anchore.contract.coverage; do not edit by hand) -->"
END = "<!-- coverage:end -->"
LANDED, PLANNED, EXCLUDED = "landed", "planned", "excluded"


@dataclass(frozen=True)
class Read:
    path: str
    status: str
    note: str


def classify() -> list[Read]:
    """Every GET of the vendor file with where it stands, in path order."""
    paths = json.loads(SOURCE.read_text(encoding="utf-8"))["paths"]
    landed = {source["path"] for source in json.loads(MANIFEST.read_text(encoding="utf-8"))["sources"]}
    rules = [(re.compile(rule["pattern"]), rule["status"], rule["reason"]) for rule in json.loads(RULES.read_text(encoding="utf-8"))["rules"]]
    out = []
    for path in sorted(paths):
        if not isinstance(paths[path], dict) or "get" not in paths[path]:
            continue
        if path in landed:
            out.append(Read(path, LANDED, ""))
            continue
        status, note = next(((status, reason) for pattern, status, reason in rules if pattern.search(path)), (PLANNED, ""))
        out.append(Read(path, status, note))
    return out


def render(reads: list[Read]) -> str:
    """The spec's coverage section: the counts, what is planned, what is landed, and what is excluded and why."""
    count = {status: sum(read.status == status for read in reads) for status in (LANDED, PLANNED, EXCLUDED)}
    lines = [
        BEGIN,
        "",
        f"Anchore's API (the committed vendor file) has {len(reads)} reads. {count[LANDED]} are landed, {count[PLANNED]} are planned and {count[EXCLUDED]} are excluded. The target is hit when none is planned.",
        "",
        "**Planned: not yet read.**",
        "",
        "| read | note |",
        "| --- | --- |",
        *[f"| `{read.path}` | {read.note} |" for read in reads if read.status == PLANNED],
        "",
        "**Landed: the collector reads it.**",
        "",
        ", ".join(f"`{read.path}`" for read in reads if read.status == LANDED) + ".",
        "",
        "**Excluded, by reason.**",
        "",
        "| reason | reads |",
        "| --- | --- |",
    ]
    by_reason: dict[str, list[str]] = {}
    for read in reads:
        if read.status == EXCLUDED:
            by_reason.setdefault(read.note, []).append(read.path)
    for reason in sorted(by_reason, key=lambda r: (-len(by_reason[r]), r)):
        paths = by_reason[reason]
        shown = ", ".join(f"`{p}`" for p in paths[:6]) + (f" and {len(paths) - 6} more" if len(paths) > 6 else "")
        lines.append(f"| {reason} | {len(paths)}: {shown} |")
    lines += ["", END]
    return "\n".join(lines)


def spec_section(text: str) -> str | None:
    """The generated section as the spec holds it, markers included; None when the spec has none."""
    if BEGIN not in text or END not in text:
        return None
    return text[text.index(BEGIN) : text.index(END) + len(END)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the spec's coverage section is not what this prints")
    args = parser.parse_args(argv)
    fresh = render(classify())
    if args.check:
        if spec_section(SPEC.read_text(encoding="utf-8")) != fresh:
            print("the spec's coverage section is stale; regenerate it with tap_plugin.anchore.contract.coverage", file=sys.stderr)
            return 1
        return 0
    sys.stdout.write(fresh + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
